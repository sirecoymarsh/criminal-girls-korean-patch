"""Generate pc/src/pc_subs_table.c: battle voice subtitles for the PC (Steam) build.

The Codex table (Vita, 11-22) is keyed by the SHA-256 of each Vita .voi entry. The PC voice banks have the same
names and entry order (btv_00_00.tpk: btl_00_00_000.ogg ...) but carry Ogg Vorbis, so a row is carried over by
(bank, index) and keyed on the PC by (Ogg size, FNV-1a of its first 4096 bytes) — what subs.c computes when the
game's voice player 0x464aa0(ch, ogg, size) runs. Text encoding = the Vita build's (Hangul -> the slot's former
kanji, UTF-8), the PC Korean patch uses the same font report.

usage: python -X utf8 gen_pc_subs.py [--all-clips]  (test: label every clip without a subtitle)
"""
import argparse
import csv
import hashlib
import struct
import sys
from pathlib import Path

sys.path.insert(0, r"P:\AI\cg-battle-subs\tools")
from gen_tables import chr_of, encode, fnv, load_font, ps3fs_entries, wrap  # noqa: E402

VITA = Path(r"P:\AI\Codex\projects\criminal-girls-invite-only-vita-ko\baseline\vpk_extracted\DATA.DAT")
PC = Path(r"F:\DOWN\Criminal.Girls.Invite.Only\Criminal.Girls.Invite.Only\Criminal Girls Invite Only\data\data_jp.dat")
CODEX = Path(r"P:\AI\Codex\projects\criminal-girls-invite-only-vita-ko\staging\battle_voice_subs_20261122\voice_subs.tsv")
OUT = Path(r"P:\AI\cg-battle-subs\pc\src\pc_subs_table.c")
HASH_BYTES = 4096
NAMES = {0: "키사라기", 1: "란", 2: "앨리스", 3: "토모에", 4: "사코", 5: "유코", 6: "신", 7: "미우", 8: "히메카미"}


def banks(path: Path):
    out = {}
    with path.open("rb") as f:
        for e in ps3fs_entries(path):
            if not (e.name.lower().startswith("btv_") and e.name.lower().endswith(".tpk")):
                continue
            f.seek(e.offset)
            b = f.read(e.size)
            n = struct.unpack_from("<I", b, 8)[0]
            ids = struct.unpack_from(f"<{n}H", b, 16)
            table = (16 + n * 2 + 3) & ~3
            ents = []
            for i in range(n):
                raw, size, off = struct.unpack_from("<40sII", b, table + i * 48)
                ents.append((ids[i], raw.split(b"\0")[0].decode("ascii", "replace"), b[off:off + size]))
            out[e.name.lower()] = ents
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--all-clips", action="store_true")
    ap.add_argument("--wrap", type=int, default=14)
    a = ap.parse_args()
    enc, former, preserved = load_font()
    rows = {}
    with CODEX.open(encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f, delimiter="\t"):
            rows[r["sha256"]] = r
    vb, pb = banks(VITA), banks(PC)
    problems, entries = [], {}
    stats = {"vita_banks": len(vb), "pc_banks": len(pb), "mapped": 0, "name_mismatch": 0, "no_pc_bank": 0,
             "key_conflict": 0, "labels": 0}
    for bank, vents in sorted(vb.items()):
        pents = pb.get(bank)
        if pents is None:
            stats["no_pc_bank"] += 1
            continue
        for i, (vid, vname, vdata) in enumerate(vents):
            if i >= len(pents):
                break
            pid, pname, pdata = pents[i]
            if pid != vid or pname.rsplit(".", 1)[0] != vname.rsplit(".", 1)[0]:
                stats["name_mismatch"] += 1
                continue
            if len(pdata) < 0x40 or pdata[:4] != b"OggS":
                continue
            key = (len(pdata), fnv(pdata[:min(HASH_BYTES, len(pdata))]))
            r = rows.get(hashlib.sha256(vdata).hexdigest())
            ko = (r["subtitle_ko"].strip() if r else "")
            if ko:
                chr_ = int(r["character_id"]) if r["character_id"].strip().isdigit() else chr_of(bank, vname)
                try:
                    ms = int(float(r["duration_seconds"]) * 1000)
                except ValueError:
                    ms = 1500
            elif a.all_clips:
                chr_ = chr_of(bank, vname)
                ko = f"{NAMES.get(chr_, '?')} 음성 {bank.replace('.tpk', '').replace('btv_', '')} {vid}"
                ms = 2000
                stats["labels"] += 1
            else:
                continue
            text = encode(wrap(ko, a.wrap), enc, former, preserved, f"{bank}#{vid}", problems)
            prev = entries.get(key)
            if prev and prev[0] != text:
                stats["key_conflict"] += 1
                continue
            if not prev:
                entries[key] = (text, chr_, ms, f"{bank}#{vid} {pname}")
                stats["mapped"] += 1
    items = sorted(entries.items(), key=lambda kv: (kv[0][1], kv[0][0]))
    lines = ["/* generated by pc/tools/gen_pc_subs.py - do not edit */\n",
             "struct sub { unsigned int size, hash; const char *text; unsigned short ms; unsigned char chr, pad; };\n"]
    for k, ((size, h), (text, chr_, ms, src)) in enumerate(items):
        lit = "".join(f"\\x{x:02x}" for x in text)
        lines.append(f"static const char T{k}[] = \"{lit}\"; /* {src} */\n")
    lines.append("const struct sub SUBS[] = {\n")
    for k, ((size, h), (text, chr_, ms, src)) in enumerate(items):
        lines.append(f"    {{{size}u, 0x{h:08x}u, T{k}, {min(ms, 65535)}, {chr_ & 0xFF}, 0}},\n")
    lines.append("};\n")
    lines.append(f"const unsigned int SUBS_N = {len(items)};\n")
    OUT.write_text("".join(lines), encoding="utf-8")
    print(stats, "problems", len(problems))
    for p in problems[:10]:
        print("PROBLEM", p)
    print("wrote", OUT, len(items))


if __name__ == "__main__":
    main()
