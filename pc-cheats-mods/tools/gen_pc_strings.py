"""Generate pc/src/pc_strings.c: the settings-screen strings (same texts as the Vita build) in the PC Korean
patch's text encoding.

The PC Korean patch draws Hangul through repurposed Shift-JIS kanji slots (font report
P:\\AI\\Codex\\projects\\criminal-girls-invite-only-ko\\staging\\korean_font_report.json, checked against the
installed exe's help line "BGM 음량을 조절합니다"). The game's text boxes take UTF-8 (0x4e9030 converts its
Shift-JIS tables with codepage 932 -> UTF-16 -> UTF-8), so each Hangul syllable becomes the UTF-8 form of its
slot kanji.

usage: python -X utf8 gen_pc_strings.py
"""
import importlib.util
import json
from pathlib import Path

VITA_GEN = Path(r"P:\AI\cg-battle-subs\tools\gen_opt_strings.py")
FONT = Path(r"P:\AI\Codex\projects\criminal-girls-invite-only-ko\staging\korean_font_report.json")
OUT = Path(r"P:\AI\cg-battle-subs\pc\src\pc_strings.c")
# PC-only texts: the PC settings font draws ASCII in wide cells, so "Mod + Decensor" ran into its value (11-23)
# and the help line box holds about 21 cells ("검열 해제 모드 (바꾼 뒤 게임을 다시 켜면 적용)" ran past it)
PC_TEXT = {"OS_M2": "검열 해제 모드", "OS_MH2": "검열 해제 (게임을 다시 켜면 적용)"}


def vita_strings():
    src = VITA_GEN.read_text(encoding="utf-8")
    start = src.index("STRINGS = [")
    end = src.index("]\n", start)
    ns = {}
    exec(src[start:end + 2], ns)  # only the literal list
    return ns["STRINGS"]


def main():
    slots = {r["char"]: int(r["sjis"], 16) for r in json.loads(FONT.read_text(encoding="utf-8-sig"))["repurposed_slots"]}
    out = ["/* generated by pc/tools/gen_pc_strings.py - do not edit */\n"]
    problems = []
    for name, text in vita_strings():
        text = PC_TEXT.get(name, text)
        b = bytearray()
        for ch in text:
            if ord(ch) < 128:
                b.append(ord(ch))
                continue
            try:
                ch.encode("cp932")
                b += ch.encode("utf-8")
                continue
            except UnicodeEncodeError:
                pass
            code = slots.get(ch)
            if code is None:
                problems.append(f"{name}: no slot for {ch!r}")
                continue
            b += code.to_bytes(2, "big").decode("cp932").encode("utf-8")
        lit = "".join(f"\\x{x:02x}" for x in b)
        out.append(f"const char {name}[] = \"{lit}\"; /* {text} */\n")
    OUT.write_text("".join(out), encoding="utf-8")
    for p in problems:
        print("PROBLEM", p)
    print(f"wrote {OUT} ({len(out) - 1} strings, {len(problems)} problems)")


if __name__ == "__main__":
    main()
